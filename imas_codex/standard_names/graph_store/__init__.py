def resolve_owned_name(name: str) -> Any:
    """Resolve a moved symbol at its owning module."""
    module = _OWNER_BY_NAME.get(name)
    if module is None:
        raise AttributeError(name)
    return getattr(import_module(f".{module}", __name__), name)


def owner_module_path(name: str) -> str:
    """Return the import path where a moved graph name is looked up."""
    return f"{__name__}.{_OWNER_BY_NAME[name]}"


